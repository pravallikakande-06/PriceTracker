import os
import smtplib

from email.message import EmailMessage

from dotenv import load_dotenv


load_dotenv()


def send_email(
    subject,
    body,
    recipient=None
):
    """Send an email using SMTP."""

    smtp_host = os.getenv("SMTP_HOST")
    smtp_port = int(
        os.getenv("SMTP_PORT", "587")
    )

    username = os.getenv("SMTP_USERNAME")
    password = os.getenv("SMTP_PASSWORD")

    recipient = (
        recipient
        or os.getenv("NOTIFICATION_EMAIL")
    )

    if not username or not password:
        raise ValueError(
            "SMTP credentials are not configured."
        )

    if not recipient:
        raise ValueError(
            "Notification email is not configured."
        )

    message = EmailMessage()

    message["Subject"] = subject
    message["From"] = username
    message["To"] = recipient

    message.set_content(body)

    with smtplib.SMTP(
        smtp_host,
        smtp_port,
        timeout=20
    ) as server:

        server.starttls()

        server.login(
            username,
            password
        )

        server.send_message(message)


def send_price_drop_alert(
    product_name,
    product_url,
    previous_price,
    current_price,
    percentage_change,
    recipient=None
):
    """Notify user when product price decreases."""

    drop_amount = (
        previous_price - current_price
    )

    subject = (
        f"Price Drop Alert: {product_name}"
    )

    body = f"""
Good news!

The price of the following product has decreased.

Product:
{product_name}

Previous price:
₹{previous_price:,.2f}

Current price:
₹{current_price:,.2f}

Price decrease:
₹{drop_amount:,.2f}

Percentage decrease:
{abs(percentage_change):.2f}%

Product URL:
{product_url}

This notification was generated by
E-Commerce Price Tracker.
"""

    send_email(
        subject,
        body,
        recipient
    )


